    locate("标签页，",True)
    shell("am","force-stop","app.terra.browser")
    shell("am","start","-n","app.terra.browser/.MainActivity")
    tap("标签页，",True)
    tap("标签组")
    tap(name)
    tap("完成")
    locate(first)
    tap("标签页，2 个")
    tap("标签组")
    if screenshot:
        locate("重新命名")
        screenshot.write_bytes(adb("exec-out","screencap","-p"))
    tap("移除标签组")
    tap("删除组并关闭标签页")
    tap("完成")
    print("PASS reopening another group after a cold restart returns to its previously selected page",flush=True)
